// A combo is turned into a cart line via a synthetic "product" so the existing
// cart/checkout flow (which keys on product._id / name / price) works unchanged.
export const comboToProduct = (combo) => ({
  _id: combo.id,
  name: combo.name,
  price: combo.price,
  discountedPrice: combo.price,
  category: 'Combo Pack',
  isCombo: true,
  comboItemCount: combo.items.reduce((a, it) => a + it.qty, 0),
});

